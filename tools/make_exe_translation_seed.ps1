$enc = [Text.Encoding]::GetEncoding(
  932,
  [Text.EncoderFallback]::ExceptionFallback,
  [Text.DecoderFallback]::ExceptionFallback
)

$rows = Get-Content -LiteralPath $source -Raw -Encoding UTF8 | ConvertFrom-Json
$errors = @()
foreach ($row in $rows) {
  if ($map.ContainsKey($row.id)) {
    $text = [string]$map[$row.id]
    try {
      $encoded = $enc.GetBytes($text)
      if ($encoded.Length -gt [int]$row.byteLength) {
        $errors += "$($row.id) too long: $($encoded.Length) > $($row.byteLength) :: $text"
      }
      $row.translation = $text
    } catch {
      $errors += "$($row.id) cannot encode :: $text :: $($_.Exception.Message)"
    }
  }
}

if ($errors.Count -gt 0) {
  $errors | ForEach-Object { Write-Error $_ }
  throw "Translation seed has $($errors.Count) errors."
}

$json = $rows | ConvertTo-Json -Depth 5
[IO.File]::WriteAllText((Join-Path (Get-Location) $output), $json, [Text.UTF8Encoding]::new($false))
Write-Output "Wrote $output with $($map.Count) seeded translations."
